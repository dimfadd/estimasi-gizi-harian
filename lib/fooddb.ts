// id yang sudah pernah dipakai TIDAK BOLEH diganti: catatan lama menyimpan id ini.

export type LogGroup = "karbo" | "lauk" | "sayur" | "buah" | "hidangan" | "camilan" | "minum" | "bumbu" | "buatanku";

export interface DbFood {
  id: string;
  name: string;
  group: LogGroup;
  unit: string;
  /** satuan tangan: ikut skala tangan pemiliknya */
  hand: boolean;
  step: 0.5 | 1;
  kcal: number;
  p: number;
  c: number;
  f: number;
  fb: number;
  /** gula tambahan bawaan per satuan (minuman kemasan, kecap, dll.) */
  sug: number;
  fryable: boolean;
  sweetable: boolean;
  aka: string;
  icon: string;
}

type Opt = Partial<{ hand: boolean; step: 0.5 | 1; fry: boolean; sweet: boolean; sug: number; aka: string; icon: string }>;

const HAND_UNITS = new Set(["kepal", "telapak", "genggam", "ibu jari"]);
const HALF_UNITS = new Set(["kepal", "telapak", "genggam", "ibu jari", "gelas", "mangkuk", "piring", "porsi", "sdm", "sdt", "ekor", "tongkol"]);
const GROUP_ICON: Record<LogGroup, string> = {
  karbo: "nasi_putih",
  lauk: "dada_ayam",
  sayur: "sayur",
  buah: "apel",
  hidangan: "piring_isi",
  camilan: "gorengan",
  minum: "susu_gelas",
  bumbu: "sambal",
  buatanku: "piring_isi",
};

const x = (id: string, name: string, group: LogGroup, unit: string, kcal: number, p: number, c: number, f: number, fb: number, o: Opt = {}): DbFood => ({
  id,
  name,
  group,
  unit,
  hand: o.hand ?? HAND_UNITS.has(unit),
  step: o.step ?? (HALF_UNITS.has(unit) ? 0.5 : 1),
  kcal,
  p,
  c,
  f,
  fb,
  sug: o.sug ?? 0,
  fryable: o.fry ?? false,
  sweetable: o.sweet ?? false,
  aka: o.aka ?? "",
  icon: o.icon ?? GROUP_ICON[group],
});

